#!/usr/bin/env python3
"""Generate docker-compose.yml for N team vulnboxes + the checksystem.

Published host ports (bound to 127.0.0.1 only):
    team i :  web   -> 9300+i
              crypto-> 9400+i
              depot -> 9500+i
    checksystem scoreboard -> SCOREBOARD_PORT (default 8090)

Usage:  python gen_compose.py [--teams N]
Reads TEAMS and SCOREBOARD_PORT from .env if not overridden.
"""
import os
import sys

WEB_BASE, CRYPTO_BASE, DEPOT_BASE = 9300, 9400, 9500
DEFAULT_SCOREBOARD_PORT = 8090


def read_env(path=".env"):
    env = {}
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip()
    return env


def build(teams, env):
    L = []
    L.append("# AUTO-GENERATED by gen_compose.py — edit .env + rerun, don't hand-edit.")
    L.append("name: adctf")
    L.append("")
    L.append("networks:")
    L.append("  ctf:")
    L.append("    driver: bridge")
    L.append("")
    L.append("volumes:")
    L.append("  checksystem-data:")
    L.append("")
    L.append("services:")

    # checksystem
    L.append("  checksystem:")
    L.append("    build:")
    L.append("      context: .")
    L.append("      dockerfile: infra/checksystem/Dockerfile")
    L.append("    image: adctf-checksystem:latest")
    L.append("    environment:")
    L.append("      TEAMS: \"%s\"" % teams)
    L.append("      TICK_SECONDS: \"%s\"" % env.get("TICK_SECONDS", "30"))
    L.append("      FLAG_LIFETIME_TICKS: \"%s\"" % env.get("FLAG_LIFETIME_TICKS", "5"))
    L.append("      GAME_SECRET: \"%s\"" % env.get("GAME_SECRET", "studentctf-local-dev-change-me"))
    L.append("      MY_TEAM: \"%s\"" % env.get("MY_TEAM", "team1"))
    sb = int(env.get("SCOREBOARD_PORT", DEFAULT_SCOREBOARD_PORT))
    L.append("    ports:")
    L.append("      - \"127.0.0.1:%d:8080\"" % sb)  # host sb -> container 8080
    L.append("    volumes:")
    L.append("      - checksystem-data:/app/data")
    L.append("    depends_on:")
    for i in range(1, teams + 1):
        L.append("      - team%d" % i)
    L.append("    networks: [ctf]")
    L.append("    restart: unless-stopped")
    L.append("")

    # teams
    for i in range(1, teams + 1):
        L.append("  team%d:" % i)
        L.append("    build:")
        L.append("      context: .")
        L.append("      dockerfile: infra/vulnbox/Dockerfile")
        L.append("    image: adctf-vulnbox:latest")
        L.append("    environment:")
        L.append("      TEAM_NAME: \"team%d\"" % i)
        L.append("    ports:")
        L.append("      - \"127.0.0.1:%d:5001\"" % (WEB_BASE + i))
        L.append("      - \"127.0.0.1:%d:5002\"" % (CRYPTO_BASE + i))
        L.append("      - \"127.0.0.1:%d:5003\"" % (DEPOT_BASE + i))
        L.append("    networks: [ctf]")
        L.append("    restart: unless-stopped")
        L.append("")

    return "\n".join(L).rstrip() + "\n"


def main():
    env = read_env()
    teams = int(env.get("TEAMS", "10"))
    args = sys.argv[1:]
    if "--teams" in args:
        teams = int(args[args.index("--teams") + 1])
    out = build(teams, env)
    with open("docker-compose.yml", "w", encoding="utf-8") as f:
        f.write(out)
    sb = int(env.get("SCOREBOARD_PORT", DEFAULT_SCOREBOARD_PORT))
    print("Wrote docker-compose.yml for %d teams (team1 = %s). Scoreboard: http://127.0.0.1:%d"
          % (teams, env.get("MY_TEAM", "team1"), sb))


if __name__ == "__main__":
    main()
